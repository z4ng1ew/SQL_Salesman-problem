### ❓ Вопрос 7: Как работает сортировка ORDER BY с двумя полями?

**Ответ:**
```
ORDER BY выполняется ПОЭТАПНО:

ORDER BY total_cost, tour

ЭТАП 1: Сортировка по total_cost (первичный ключ)
Группирует строки по стоимости:
[80, 80, 95, 95, 95, 95]

ЭТАП 2: Внутри каждой группы сортировка по tour (вторичный ключ)
Группа total_cost=80:
  {a,b,d,c,a}  ← 'b' на 3-й позиции
  {a,c,d,b,a}  ← 'c' на 3-й позиции, 'c' > 'b'

Группа total_cost=95:
  {a,b,c,d,a}
  {a,c,b,d,a}
  {a,d,b,c,a}
  {a,d,c,b,a}

Лексикографическое сравнение = посимвольное слева направо

Аналогия в JavaScript:
data.sort((a, b) => {
    if (a.cost !== b.cost) return a.cost - b.cost;  // сначала по cost
    return a.tour.localeCompare(b.tour);            // потом по tour
});
```

