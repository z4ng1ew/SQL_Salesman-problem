## 🎓 ОТВЕТЫ НА ВОЗМОЖНЫЕ ВОПРОСЫ ПРИ ЗАЩИТЕ

### ❓ Вопрос 1: В чём главное отличие ex01 от ex00?

**Ответ:**
```
Различие ТОЛЬКО в финальной фильтрации:

EX00 (Classical TSP):
WHERE total_cost = (SELECT MIN(total_cost) FROM complete_cycles)
→ Выводит ТОЛЬКО минимальные маршруты

EX01 (Opposite TSP):
WHERE total_cost = (SELECT MIN(...)) OR total_cost = (SELECT MAX(...))
→ Выводит И минимальные, И максимальные маршруты

Всё остальное (рекурсия, построение путей, возврат в 'a') — ИДЕНТИЧНО!

Название "Opposite" = противоположные крайности (MIN + MAX)
```

---

### ❓ Вопрос 2: Почему файл ex01 не содержит CREATE TABLE?

**Ответ:**
```
По требованию задания:

EX00: "DDL for table creation with INSERTs of data; SQL DML statement"
→ CREATE + INSERT + SELECT

EX01: "SQL DML statement"
→ ТОЛЬКО SELECT

Логика проверки:
1. Reviewer запускает ex00 → создаётся таблица tsp
2. Reviewer запускает ex01 → использует уже существующую таблицу

DML = Data Manipulation Language (работа с данными)
DDL = Data Definition Language (создание структуры)

Ex01 манипулирует данными, но не создаёт структуру.
```

---

### ❓ Вопрос 3: Зачем промежуточный CTE `min_and_max_routes`?

**Ответ:**
```
Это ОПЦИОНАЛЬНЫЙ стилистический выбор для улучшения читаемости.

Можно было бы БЕЗ него:

SELECT total_cost, tour
FROM complete_cycles
WHERE total_cost = (SELECT MIN(...)) OR total_cost = (SELECT MAX(...))
ORDER BY total_cost, tour;

Преимущества min_and_max_routes:
✅ Логическое разделение этапов (фильтрация отдельно от вывода)
✅ Улучшенная читаемость (понятно, что делает каждый блок)
✅ Легче расширять (можно добавить дополнительные фильтры)
✅ Самодокументирование (имя CTE объясняет содержимое)

Это признак профессионального подхода к написанию SQL.
```

