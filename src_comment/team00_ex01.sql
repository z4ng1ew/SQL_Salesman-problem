### ❓ Вопрос 8: Можно ли обойтись без всех трёх CTE?

**Ответ:**
```
Технически ДА, но код станет НЕЧИТАЕМЫМ:

Минимальная версия (всё в одном):

WITH RECURSIVE x AS (
    SELECT ARRAY['a']::varchar[] p, 'a'::char c, 0 s
    UNION ALL
    SELECT x.p||ARRAY[t.point2]::varchar[], t.point2, x.s+t.cost
    FROM x JOIN tsp t ON t.point1=x.c WHERE NOT t.point2=ANY(x.p)
)
SELECT x.s+t.cost AS total_cost,
       '{'||array_to_string(x.p||ARRAY['a']::varchar[],',')||'}' AS tour
FROM x JOIN tsp t ON t.point1=x.c AND t.point2='a'
WHERE array_length(x.p,1)=(SELECT COUNT(DISTINCT point1) FROM tsp)
  AND (x.s+t.cost=(SELECT MIN(...) FROM (...))
   OR  x.s+t.cost=(SELECT MAX(...) FROM (...)))
ORDER BY 1,2;

