### ❓ Вопрос 4: Что будет, если MIN = MAX?

**Ответ:**
```
Вырожденный случай: все циклы имеют одинаковую стоимость.

Пример графа:
Все рёбра стоят одинаково (например, по 10)
→ Любой маршрут будет стоить 40

Тогда:
MIN(total_cost) = 40
MAX(total_cost) = 40

Условие WHERE:
total_cost = 40 OR total_cost = 40
→ Эквивалентно: total_cost = 40

Результат: выведутся ВСЕ 6 маршрутов
(т.к. они все одновременно и MIN, и MAX)

Это КОРРЕКТНОЕ поведение для вырожденного случая!
```

---

### ❓ Вопрос 5: Почему OR, а не UNION?

**Ответ:**
```
OR эффективнее, чем UNION:

Вариант 1: OR (наш выбор)
WHERE total_cost = MIN(...) OR total_cost = MAX(...)
✅ Один проход по таблице complete_cycles
✅ Один результирующий набор
✅ Короче и понятнее

Вариант 2: UNION
(SELECT * FROM complete_cycles WHERE total_cost = MIN(...))
UNION
(SELECT * FROM complete_cycles WHERE total_cost = MAX(...))
❌ Два прохода по таблице
❌ Два отдельных запроса склеиваются
❌ Медленнее
❌ Длиннее код

Оба дадут одинаковый результат, но OR оптимальнее!

Плюс UNION удалит дубликаты (если MIN=MAX), а UNION ALL нет.
```

---

### ❓ Вопрос 6: Сколько раз выполняются подзапросы MIN/MAX?

**Ответ:**
```
Кажется, что для каждой строки, но PostgreSQL ОПТИМИЗИРУЕТ!

В коде видим:
WHERE total_cost = (SELECT MIN(...)) OR total_cost = (SELECT MAX(...))

Кажется: для каждой строки выполняется 2 подзапроса

Реальность: PostgreSQL умный!
1. Анализирует план выполнения
2. Видит, что подзапросы не зависят от текущей строки
3. Выполняет их ОДИН РАЗ перед основным запросом
4. Кэширует результаты
5. Использует кэшированные значения для проверки

EXPLAIN покажет:
InitPlan 1 (returns $0) → MIN выполнен 1 раз
InitPlan 2 (returns $1) → MAX выполнен 1 раз
Seq Scan on complete_cycles → проверка WHERE с $0 и $1

Это называется "subquery pull-up optimization"
```

