### 1️⃣ **Фильтрация MIN и MAX**

```sql
-- Вариант 1: OR (наш выбор, лучший)
WHERE total_cost = (SELECT MIN(total_cost) FROM complete_cycles)
   OR total_cost = (SELECT MAX(total_cost) FROM complete_cycles)
✅ Один проход по таблице
✅ Короткий и понятный
✅ Эффективный

-- Вариант 2: IN с двумя значениями
WHERE total_cost IN (
    (SELECT MIN(total_cost) FROM complete_cycles),
    (SELECT MAX(total_cost) FROM complete_cycles)
)
✅ Тоже работает хорошо
⚠️ Чуть менее явно (скрывает логику OR)

-- Вариант 3: UNION
(SELECT * FROM complete_cycles 
 WHERE total_cost = (SELECT MIN(total_cost) FROM complete_cycles))
UNION
(SELECT * FROM complete_cycles 
 WHERE total_cost = (SELECT MAX(total_cost) FROM complete_cycles))
❌ Два прохода по таблице
❌ Избыточно
⚠️ UNION удалит дубликаты (если MIN=MAX)

-- Вариант 4: Window функции
SELECT total_cost, tour
FROM (
    SELECT *,
           MIN(total_cost) OVER () as min_cost,
           MAX(total_cost) OVER () as max_cost
    FROM complete_cycles
) sub
WHERE total_cost = min_cost OR total_cost = max_cost
✅ Один проход
⚠️ Сложнее для понимания
⚠️ Избыточно для простой задачи

-- Вариант 5: BETWEEN (НЕПРАВИЛЬНО!)
WHERE total_cost BETWEEN 
    (SELECT MIN(total_cost) FROM complete_cycles) 
    AND (SELECT MAX(total_cost) FROM complete_cycles)
❌ Выведет ВСЕ маршруты, включая промежуточные!
❌ Не соответствует заданию
```

**Рейтинг:**
1. ✅ Вариант 1 (OR) — оптимальный
2. ✅ Вариант 2 (IN) — хорошая альтернатива
3. ⚠️ Вариант 4 (Window) — избыточен
4. ❌ Вариант 3 (UNION) — неэффективен
5. ❌ Вариант 5 (BETWEEN) — неправильно!

