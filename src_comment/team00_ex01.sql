-- ==========================================
-- ЗАДАЧА КОММИВОЯЖЁРА - OPPOSITE TSP
-- Вывод MIN и MAX маршрутов
-- ==========================================

WITH RECURSIVE building_routes AS (
    -- База рекурсии: начинаем путь с города 'a'
    SELECT
        ARRAY['a']::varchar[]  AS visited_cities,
        'a'::CHAR(1)           AS current_city,
        0                      AS accumulated_cost
    
    UNION ALL
    
    -- Рекурсивный шаг: добавляем непосещённые города
    SELECT
        routes.visited_cities || ARRAY[edges.point2]::varchar[],
        edges.point2,
        routes.accumulated_cost + edges.cost
    FROM building_routes AS routes
    JOIN tsp AS edges ON edges.point1 = routes.current_city
    WHERE NOT edges.point2 = ANY(routes.visited_cities)
),

complete_cycles AS (
    -- Завершаем маршруты возвратом в начальную точку 'a'
    SELECT
        routes.accumulated_cost + return_edge.cost AS total_cost,
        '{' || array_to_string(routes.visited_cities || ARRAY['a']::varchar[], ',') || '}' AS tour
    FROM building_routes AS routes
    JOIN tsp AS return_edge 
      ON return_edge.point1 = routes.current_city 
     AND return_edge.point2 = 'a'
    WHERE array_length(routes.visited_cities, 1) = (
        SELECT COUNT(DISTINCT point1) FROM tsp
    )
),

min_and_max_routes AS (
    -- Отбираем маршруты с минимальной и максимальной стоимостью
    SELECT total_cost, tour
    FROM complete_cycles
    WHERE total_cost = (SELECT MIN(total_cost) FROM complete_cycles)
       OR total_cost = (SELECT MAX(total_cost) FROM complete_cycles)
)

SELECT total_cost, tour
FROM min_and_max_routes
ORDER BY total_cost, tour;






















# 📚 ПОДРОБНАЯ ДОКУМЕНТАЦИЯ team00_ex01.sql ДЛЯ ЗАЩИТЫ

```sql
-- ==========================================
-- РЕШЕНИЕ ЗАДАЧИ КОММИВОЯЖЁРА - OPPOSITE TSP
-- Exercise 01: Вывод маршрутов с минимальной И максимальной стоимостью
-- 
-- ОТЛИЧИЕ ОТ EX00:
-- Ex00 выводит только MIN маршруты
-- Ex01 выводит MIN И MAX маршруты
--
-- Автор: [твоё имя]
-- Дата: [дата]
-- ==========================================

-- ВАЖНО: Этот файл содержит ТОЛЬКО DML (SELECT-запрос)
-- Таблица tsp уже создана и заполнена в ex00
-- Это соответствует требованию задания: "SQL DML statement"

-- ============================================
-- ЧАСТЬ 1: РЕКУРСИВНОЕ ПОСТРОЕНИЕ МАРШРУТОВ
-- ============================================

-- WITH RECURSIVE создаёт рекурсивный Common Table Expression (CTE)
-- CTE = временная именованная результирующая таблица
-- RECURSIVE разрешает CTE ссылаться на саму себя (рекурсия)
WITH RECURSIVE building_routes AS (
    
    -- ----------------------------------------
    -- БАЗА РЕКУРСИИ (anchor member)
    -- Начальное состояние: стоим в городе 'a'
    -- ----------------------------------------
    SELECT
        -- visited_cities - массив посещённых городов
        -- ARRAY['a'] создаёт одноэлементный массив PostgreSQL
        -- ::varchar[] - явное приведение типа к "массив строк переменной длины"
        -- 
        -- Зачем явное приведение:
        -- PostgreSQL должен знать точный тип для последующих операций (||)
        ARRAY['a']::varchar[]  AS visited_cities,
        
        -- current_city - текущее местоположение коммивояжёра
        -- Начинаем с 'a' согласно условию задачи
        -- ::CHAR(1) - приведение к типу "ровно 1 символ"
        'a'::CHAR(1)           AS current_city,
        
        -- accumulated_cost - накопленная стоимость пройденного пути
        -- Изначально 0, т.к. мы ещё не двигались
        -- 
        -- НАЗВАНИЕ "accumulated" важно:
        -- Это НЕ финальная стоимость (мы ещё не вернулись в 'a')
        -- Это стоимость "на данный момент"
        0                      AS accumulated_cost
    
    -- UNION ALL объединяет базу рекурсии с рекурсивным шагом
    -- ALL означает "не удалять дубликаты"
    -- Зачем ALL: нам нужны ВСЕ варианты маршрутов, даже если промежуточные состояния похожи
    UNION ALL
    
    -- ----------------------------------------
    -- РЕКУРСИВНЫЙ ШАГ (recursive member)
    -- Добавление следующего непосещённого города к маршруту
    -- Выполняется многократно, пока есть новые строки
    -- ----------------------------------------
    SELECT
        -- Расширяем массив посещённых городов
        -- || - оператор конкатенации (склеивания) для массивов и строк
        -- routes.visited_cities - массив из предыдущей итерации
        -- ARRAY[edges.point2]::varchar[] - следующий город, завёрнутый в массив
        -- 
        -- Почему завёрнут в ARRAY: оператор || работает массив+массив
        -- Результат: новый массив с добавленным элементом
        routes.visited_cities || ARRAY[edges.point2]::varchar[],
        
        -- Обновляем текущую позицию
        -- Теперь мы находимся в городе, в который только что переместились
        edges.point2,
        
        -- Увеличиваем накопленную стоимость
        -- Прибавляем стоимость последнего перехода к накопленной сумме
        routes.accumulated_cost + edges.cost
    
    -- FROM указывает источник данных для рекурсивного шага
    -- building_routes - ссылка на РЕЗУЛЬТАТ предыдущей итерации рекурсии
    -- AS routes - короткий алиас для читаемости
    FROM building_routes AS routes
    
    -- JOIN связывает текущий маршрут с возможными следующими шагами
    -- Ищем все рёбра графа, которые начинаются в текущем городе
    -- 
    -- tsp AS edges - даём таблице понятное имя "рёбра"
    -- Подчёркивает роль: это возможные переходы из текущей точки
    JOIN tsp AS edges 
      ON edges.point1 = routes.current_city
    
    -- УСЛОВИЕ ПРОДОЛЖЕНИЯ РЕКУРСИИ
    WHERE
        -- Фильтр: следующий город НЕ должен быть уже посещён
        -- 
        -- edges.point2 - город-кандидат для следующего шага
        -- ANY(массив) - агрегатная функция PostgreSQL "есть ли элемент в массиве"
        -- NOT ... = ANY(...) - логическая инверсия: "элемента НЕТ в массиве"
        -- 
        -- Эквивалентные записи:
        -- NOT (edges.point2 = ANY(routes.visited_cities))
        -- edges.point2 <> ALL(routes.visited_cities)
        -- 
        -- Это условие обеспечивает:
        -- 1. Отсутствие циклов (каждый город только 1 раз)
        -- 2. Корректность маршрута
        -- 3. Завершение рекурсии (когда все города посещены)
        NOT edges.point2 = ANY(routes.visited_cities)
        
    -- УСЛОВИЕ ОСТАНОВКИ РЕКУРСИИ (неявное):
    -- Когда все города посещены, WHERE не найдёт подходящих рёбер
    -- → рекурсивный шаг не произведёт новых строк
    -- → рекурсия автоматически завершится
    -- 
    -- PostgreSQL также защищён от бесконечной рекурсии:
    -- По умолчанию есть внутренний лимит итераций
),

-- ============================================
-- ЧАСТЬ 2: ФОРМИРОВАНИЕ ЗАВЕРШЁННЫХ ЦИКЛОВ
-- ============================================

-- complete_cycles - CTE с полными гамильтоновыми циклами
-- Гамильтонов цикл = путь через все вершины графа ровно 1 раз с возвратом
complete_cycles AS (
    
    -- Выбираем из построенных маршрутов и добавляем возврат в 'a'
    SELECT
        -- Вычисляем ФИНАЛЬНУЮ стоимость полного цикла
        -- 
        -- routes.accumulated_cost - стоимость обхода всех городов
        -- return_edge.cost - стоимость ребра для возврата в 'a'
        -- 
        -- ТОЛЬКО ЗДЕСЬ получаем полную стоимость цикла!
        -- В building_routes была только частичная (до возврата)
        routes.accumulated_cost + return_edge.cost AS total_cost,
        
        -- Формируем строковое представление маршрута в требуемом формате
        -- Требование задания: {a,b,d,c,a}
        -- 
        -- ПОШАГОВОЕ ПРЕОБРАЗОВАНИЕ:
        -- 
        -- Шаг 1: routes.visited_cities || ARRAY['a']::varchar[]
        --        Добавляем 'a' в конец массива (возврат в начало)
        --        Было: ['a','b','d','c']
        --        Стало: ['a','b','d','c','a']
        -- 
        -- Шаг 2: array_to_string(..., ',')
        --        Преобразуем массив в строку с разделителем ','
        --        PostgreSQL-функция для склеивания элементов массива
        --        Результат: "a,b,d,c,a"
        -- 
        -- Шаг 3: '{' || ... || '}'
        --        Обрамляем фигурными скобками
        --        || - оператор конкатенации строк
        --        Финальный результат: "{a,b,d,c,a}"
        -- 
        -- ПОЧЕМУ ФИГУРНЫЕ СКОБКИ:
        -- Это стандартный формат вывода PostgreSQL для массивов
        -- Соответствует требованию задания
        '{' || array_to_string(routes.visited_cities || ARRAY['a']::varchar[], ',') || '}' AS tour
    
    -- Источник данных: маршруты из рекурсивного построения
    FROM building_routes AS routes
    
    -- JOIN для поиска ребра возврата в начальную точку
    -- return_edge - специализированный алиас, подчёркивающий роль
    -- Это НЕ обычное ребро для продвижения, а специальное для замыкания цикла
    JOIN tsp AS return_edge 
      -- Условие 1: ребро должно начинаться в текущем (последнем) городе маршрута
      ON return_edge.point1 = routes.current_city 
      -- Условие 2: ребро должно заканчиваться в 'a' (замыкание цикла)
     AND return_edge.point2 = 'a'
    
    -- ПРОВЕРКА ПОЛНОТЫ МАРШРУТА
    -- Берём только те маршруты, которые посетили ВСЕ города
    WHERE
        -- Сравниваем длину массива посещённых городов с общим количеством городов
        -- 
        -- array_length(массив, измерение) - функция PostgreSQL
        -- Параметр 1: массив для измерения
        -- Параметр 2: номер измерения (для одномерных всегда 1)
        -- 
        -- COUNT(DISTINCT point1) - подсчёт уникальных городов в графе
        -- DISTINCT убирает дубликаты (каждый город дважды в таблице: как point1 и point2)
        -- 
        -- ДИНАМИЧЕСКИЙ ПОДХОД:
        -- Не используем фиксированное число (например, = 4)
        -- Код работает для ЛЮБОГО количества городов!
        -- При добавлении 5-го города ничего менять не нужно
        array_length(routes.visited_cities, 1) = (
            SELECT COUNT(DISTINCT point1) FROM tsp
        )
        
    -- РЕЗУЛЬТАТ CTE:
    -- Таблица с полными циклами, содержащая:
    -- - total_cost: полная стоимость цикла
    -- - tour: маршрут в формате {a,b,d,c,a}
),

-- ============================================
-- ЧАСТЬ 3: ФИЛЬТРАЦИЯ MIN И MAX МАРШРУТОВ
-- ============================================

-- min_and_max_routes - CTE с отфильтрованными маршрутами
-- КЛЮЧЕВОЕ ОТЛИЧИЕ ОТ EX00: здесь отбираем И минимум, И максимум
min_and_max_routes AS (
    
    -- Выбираем маршруты, стоимость которых равна минимальной ИЛИ максимальной
    SELECT 
        total_cost,  -- финальная стоимость цикла
        tour         -- маршрут в формате строки
    FROM complete_cycles
    
    -- ДВОЙНОЕ УСЛОВИЕ ФИЛЬТРАЦИИ
    WHERE
        -- Условие 1: стоимость равна минимальной
        -- MIN - агрегатная функция "найти минимум"
        -- Подзапрос выполняется ОДИН РАЗ (PostgreSQL кэширует результат)
        total_cost = (SELECT MIN(total_cost) FROM complete_cycles)
        
        -- OR - логический оператор "ИЛИ"
        -- Достаточно выполнения ХОТЯ БЫ ОДНОГО условия
        -- Маршрут попадёт в результат, если он либо MIN, либо MAX
       OR 
       
        -- Условие 2: стоимость равна максимальной
        -- MAX - агрегатная функция "найти максимум"
        -- Также выполняется один раз и кэшируется
        total_cost = (SELECT MAX(total_cost) FROM complete_cycles)
        
    -- ВОЗМОЖНЫЕ СЦЕНАРИИ:
    -- 
    -- Сценарий 1 (обычный): MIN ≠ MAX
    -- Например: MIN=80, MAX=95
    -- Результат: все маршруты с cost=80 и все с cost=95
    -- 
    -- Сценарий 2 (вырожденный): MIN = MAX
    -- Все циклы имеют одинаковую стоимость
    -- Результат: ВСЕ маршруты (т.к. они все одновременно и MIN, и MAX)
    -- 
    -- Сценарий 3 (промежуточные значения):
    -- Есть циклы с cost=85 (между 80 и 95)
    -- Результат: эти циклы НЕ попадут в вывод
)

-- ============================================
-- ЧАСТЬ 4: ФИНАЛЬНЫЙ ВЫВОД
-- ============================================

-- Финальный SELECT - вывод результатов пользователю
SELECT 
    total_cost,  -- стоимость маршрута
    tour         -- маршрут в формате {a,b,d,c,a}
FROM min_and_max_routes

-- СОРТИРОВКА РЕЗУЛЬТАТОВ
-- ORDER BY упорядочивает строки согласно требованию задания
ORDER BY 
    -- Первичная сортировка: по стоимости (ascending = по возрастанию)
    -- Результат: сначала MIN маршруты, потом MAX маршруты
    total_cost,
    
    -- Вторичная сортировка: по маршруту (лексикографически)
    -- Лексикографическая = посимвольное сравнение (как в словаре)
    -- 
    -- Пример:
    -- {a,b,d,c,a} < {a,c,d,b,a}  ← на 3-й позиции 'b' < 'c'
    -- 
    -- Это гарантирует:
    -- 1. Детерминированный порядок (всегда одинаковый)
    -- 2. Удобство при проверке (можно сравнить построчно)
    tour;

-- ============================================
-- ОЖИДАЕМЫЙ РЕЗУЛЬТАТ
-- ============================================
--
--  total_cost |     tour      
-- ------------+---------------
--          80 | {a,b,d,c,a}   ← минимальные
--          80 | {a,c,d,b,a}   ← минимальные
--          95 | {a,b,c,d,a}   ← максимальные
--          95 | {a,c,b,d,a}   ← максимальные
--          95 | {a,d,b,c,a}   ← максимальные
--          95 | {a,d,c,b,a}   ← максимальные
-- (6 rows)
--
-- Интерпретация:
-- - Минимальная стоимость: 80 (2 маршрута)
-- - Максимальная стоимость: 95 (4 маршрута)
-- - Всего выведено: 6 маршрутов
-- - Порядок: сначала дешёвые, потом дорогие
-- ============================================
```

