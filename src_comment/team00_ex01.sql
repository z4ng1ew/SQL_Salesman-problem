## 💡 КЛЮЧЕВЫЕ ОТЛИЧИЯ EX00 vs EX01

| Аспект | Exercise 00 | Exercise 01 |
|--------|-------------|-------------|
| **Файл содержит** | DDL + INSERT + SELECT | Только SELECT |
| **Фильтрация** | WHERE = MIN | WHERE = MIN OR = MAX |
| **Количество CTE** | 2 (building, complete) | 3 (building, complete, filtered) |
| **Результатов** | 2 маршрута (80) | 6 маршрутов (80+95) |
| **Название** | Classical TSP | Opposite TSP |
| **Сложность** | Проще | Чуть сложнее |

