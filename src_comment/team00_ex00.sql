### ❓ Вопрос 4: Почему `UNION ALL`, а не просто `UNION`?

**Ответ:**
```
UNION ALL сохраняет все строки, UNION удаляет дубликаты.

В нашем случае:
✅ UNION ALL - нужны ВСЕ варианты маршрутов
❌ UNION - удалил бы уникальные пути

Также UNION ALL быстрее (не тратит время на поиск дубликатов).

В рекурсивных запросах почти всегда используют UNION ALL.
```

