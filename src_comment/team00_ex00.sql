### ❓ Вопрос 8: Зачем алиасы `edges` и `return_edge`?

**Ответ:**
```
Для улучшения ЧИТАЕМОСТИ и разделения РОЛЕЙ:

JOIN tsp AS edges
→ "соединяемся с рёбрами графа для продвижения вперёд"

JOIN tsp AS return_edge  
→ "ищем специальное ребро для возврата в 'a'"

Это та же таблица tsp, но роли разные!
Алиасы делают намерение кода явным.

Аналогия:
Person employee = new Person();  // роль: сотрудник
Person customer = new Person();  // роль: клиент
```

