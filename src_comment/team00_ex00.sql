### ❓ Вопрос 7: Почему используете `COUNT(DISTINCT point1)` вместо фиксированного числа?

**Ответ:**
```
Это делает код УНИВЕРСАЛЬНЫМ (динамическим)

Плохо (жёстко зашито):
WHERE array_length(visited_cities, 1) = 4
→ Работает только для 4 городов

Хорошо (динамически):
WHERE array_length(visited_cities, 1) = (SELECT COUNT(DISTINCT point1) FROM tsp)
→ Работает для ЛЮБОГО количества городов!

Если добавить 5-й, 10-й город - код не нужно менять.
Это признак профессионального подхода.
```

