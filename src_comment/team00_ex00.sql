### ❓ Вопрос 1: Почему выбрали именно такие имена переменных?

**Ответ:**
```
Я следовал принципу self-documenting code (самодокументирующийся код):

building_routes - сразу понятно, что строим маршруты
visited_cities - ясно, что это посещённые города
current_city - текущее местоположение
accumulated_cost - накопленная (не финальная) стоимость

Это делает код понятным даже человеку, который видит его впервые.
На защите проще объяснять логику работы.
```

