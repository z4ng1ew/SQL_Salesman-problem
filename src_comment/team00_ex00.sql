###❓ Вопрос 5: Что такое `::varchar[]` и зачем оно нужно?

**Ответ:**
```
:: это оператор приведения типа (type cast)

ARRAY['a'] создаёт массив, но PostgreSQL не всегда знает точный тип
::varchar[] явно указывает: "массив строк переменной длины"

Зачем нужно:
- Для корректной конкатенации массивов (||)
- Для совместимости типов в UNION
- Для предотвращения неявных преобразований

Аналогия в C:
(char**)array  ← явное приведение типа указателя
```

