### ❓ Вопрос 6: Как работает `array_length(массив, 1)`?

**Ответ:**
```
array_length возвращает размер массива по указанному измерению

Синтаксис: array_length(массив, измерение)

Примеры:
array_length(ARRAY['a','b','c'], 1)  → 3
array_length(ARRAY['a'], 1)          → 1
array_length(ARRAY[]::varchar[], 1)  → NULL (пустой массив)

Параметр 1 = первое измерение (для одномерных массивов всегда 1)

Для многомерных массивов:
array_length(ARRAY[[1,2],[3,4]], 1)  → 2 (строки)
array_length(ARRAY[[1,2],[3,4]], 2)  → 2 (столбцы)
```

