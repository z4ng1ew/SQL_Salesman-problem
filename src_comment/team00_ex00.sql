-- ==========================================
-- ЗАДАЧА КОММИВОЯЖЁРА (TSP)
-- Улучшенная версия с понятными именами
-- ==========================================





-- TSP = Traveling Salesman Problem

-- Расшифровка:
-- T = Traveling   (путешествующий)
-- S = Salesman    (продавец, коммивояжёр)
-- P = Problem     (задача)

-- По-русски: "Задача коммивояжёра"


-- Коммивояжёр = странствующий торговец, который:

-- Ездит по городам
-- Продаёт товары
-- Хочет найти самый короткий/дешёвый маршрут
-- Таблица tsp = граф для этой задачи (города и дороги между ними)






-- Удаляем таблицу если существует
DROP TABLE IF EXISTS tsp CASCADE;

-- Создаём таблицу графа (рёбер между городами)
CREATE TABLE tsp (
    point1 CHAR(1),  -- начальный город (откуда)
    point2 CHAR(1),  -- конечный город (куда)
    cost   INT       -- стоимость перемещения
);

-- Заполняем граф данными (все рёбра двусторонние)
INSERT INTO tsp VALUES
('a','b',10), ('b','a',10),
('a','c',15), ('c','a',15),
('a','d',20), ('d','a',20),
('b','c',35), ('c','b',35),
('b','d',25), ('d','b',25),
('c','d',30), ('d','c',30);

-- ============================================
-- РЕКУРСИВНОЕ ПОСТРОЕНИЕ МАРШРУТОВ
-- ============================================

WITH RECURSIVE building_routes AS (
    -- База рекурсии: начинаем с города 'a'
    SELECT
        ARRAY['a']::varchar[]  AS visited_cities,
        'a'::CHAR(1)           AS current_city,
        0                      AS accumulated_cost
    
    UNION ALL
    
    -- Рекурсивный шаг: добавляем следующий город
    SELECT
        routes.visited_cities || ARRAY[edges.point2]::varchar[],
        edges.point2,
        routes.accumulated_cost + edges.cost
    FROM building_routes AS routes
    JOIN tsp AS edges ON edges.point1 = routes.current_city
    WHERE NOT edges.point2 = ANY(routes.visited_cities)
),

-- ============================================
-- ЗАВЕРШЁННЫЕ ЦИКЛЫ (возврат в 'a')
-- ============================================

complete_cycles AS (
    SELECT
        routes.accumulated_cost + return_edge.cost AS total_cost,
        '{' || array_to_string(routes.visited_cities || ARRAY['a']::varchar[], ',') || '}' AS tour
    FROM building_routes AS routes
    JOIN tsp AS return_edge 
      ON return_edge.point1 = routes.current_city 
     AND return_edge.point2 = 'a'
    WHERE array_length(routes.visited_cities, 1) = (
        SELECT COUNT(DISTINCT point1) FROM tsp
    )
)

-- ============================================
-- ФИНАЛЬНЫЙ РЕЗУЛЬТАТ: только минимальные
-- ============================================

SELECT total_cost, tour
FROM complete_cycles
WHERE total_cost = (SELECT MIN(total_cost) FROM complete_cycles)
ORDER BY total_cost, tour;

















# 📚 ПОДРОБНАЯ ДОКУМЕНТАЦИЯ ДЛЯ ЗАЩИТЫ (УЛУЧШЕННАЯ ВЕРСИЯ)


-- ==========================================
-- РЕШЕНИЕ ЗАДАЧИ КОММИВОЯЖЁРА (TSP)
-- Traveling Salesman Problem - Classical Version
-- 
-- Задача: найти маршрут минимальной стоимости,
-- который проходит через все города ровно 1 раз
-- и возвращается в начальную точку
--
-- Автор: [твоё имя]
-- Дата: [дата]
-- ==========================================

-- ============================================
-- ЧАСТЬ 1: ПОДГОТОВКА СТРУКТУРЫ ДАННЫХ
-- ============================================

-- Удаляем таблицу если она существует (идемпотентность)
-- CASCADE удаляет также все зависимые объекты (VIEW, constraints)
-- IF EXISTS предотвращает ошибку, если таблицы нет
DROP TABLE IF EXISTS tsp CASCADE;

-- Создаём таблицу для представления графа
-- Граф хранится как список рёбер (edge list representation)
-- Каждое ребро = переход между двумя городами
CREATE TABLE tsp (
    -- point1 - начальная вершина ребра (исходный город)
    -- CHAR(1) = фиксированная строка ровно из 1 символа
    -- Эффективнее VARCHAR(1) для однобуквенных значений
    point1 CHAR(1),
    
    -- point2 - конечная вершина ребра (город назначения)
    point2 CHAR(1),
    
    -- cost - вес ребра (стоимость перемещения)
    -- INT = целое число от -2 147 483 648 до 2 147 483 647
    cost   INT
);


point1 CHAR(1)
│      │    │
│      │    └─── (1) = количество символов (ровно 1 символ)  (не больше, не меньше)
│      │
│      └──────── CHAR = тип данных (символьная строка фиксированной длины)
│
└─────────────── point1 = название колонки (столбца)


🆚 CHAR vs VARCHAR

-- CHAR(1) - фиксированная длина (РОВНО 1 символ)
point1 CHAR(1)
'a'    → сохраняет 'a'
'ab'   → ОШИБКА! (слишком много)

-- VARCHAR(1) - переменная длина (ДО 1 символа)
point1 VARCHAR(1)
'a'    → сохраняет 'a'
'ab'   → ОШИБКА! (слишком много)
''     → сохраняет '' (пустая строка) ✅


Для нашей задачи:
CHAR(1)     ← используем это (города = 1 буква: a, b, c, d)
VARCHAR(1)  ← можно, но CHAR эффективнее для фиксированного размера

-- РЕЗУЛЬТАТ:
--  point1 | point2 | cost 
-- --------+--------+------
--  a      | b      |   10
--  a      | c      |   15
--  a      | d      |   20
--  b      | a      |   10
--  b      | c      |   35
--  b      | d      |   25
--  c      | a      |   15
--  c      | b      |   35
--  c      | d      |   30
--  d      | a      |   20
--  d      | b      |   25
--  d      | c      |   30



--  КАЖДАЯ СТРОКА = ВОЗМОЖНЫЙ ПЕРЕХОД:
--    "Если я в городе point1, могу пойти в point2 за cost"







-- Заполняем таблицу данными графа
-- Граф НЕОРИЕНТИРОВАННЫЙ: каждое ребро указано в ОБА направления
