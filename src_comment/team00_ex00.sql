### ❓ Вопрос 2: Как работает рекурсия в вашем решении?

**Ответ:**
```
Рекурсия работает в два этапа:

БАЗА (anchor):
visited_cities = ['a'], current_city = 'a', cost = 0

РЕКУРСИВНЫЙ ШАГ:
Итерация 1: Из 'a' идём в b, c, d
  → ['a','b'], ['a','c'], ['a','d']
  
Итерация 2: Из каждого продолжаем в непосещённые
  → ['a','b','c'], ['a','b','d'], ['a','c','b'], ...
  
Итерация 3: Добавляем последний город
  → ['a','b','c','d'], ['a','b','d','c'], ...

ОСТАНОВКА: когда все города посещены, условие WHERE становится ложным
```

