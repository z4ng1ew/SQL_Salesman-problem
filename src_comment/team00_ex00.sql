-- ============================================
-- ЧАСТЬ 2: РЕКУРСИВНОЕ ПОСТРОЕНИЕ МАРШРУТОВ
-- ============================================

-- WITH RECURSIVE объявляет рекурсивный Common Table Expression (CTE)
-- CTE = временная именованная таблица, существующая только в рамках запроса
-- RECURSIVE позволяет CTE ссылаться на саму себя (рекурсия)
WITH RECURSIVE building_routes AS (
    
    -- ----------------------------------------
    -- БАЗА РЕКУРСИИ (anchor member - ведущий член)
    -- Первая итерация: начальное состояние
    -- ----------------------------------------
    SELECT
        -- visited_cities - массив посещённых городов
        -- ARRAY['a'] создаёт PostgreSQL-массив с одним элементом
        -- ::varchar[] явно указывает тип "массив строк переменной длины"
        -- Зачем явное приведение: PostgreSQL должен знать точный тип для конкатенации

        ARRAY['a']::varchar[]  AS visited_cities,


-- Хотя в некоторых СУБД тип character(n) работает быстрее других, в PostgreSQL это не так; на деле character(n) обычно оказывается медленнее остальных типов из-за большего размера данных и более медленной сортировки. В большинстве случаев вместо него лучше применять text или character varying.
-- https://postgrespro.ru/docs/postgresql/18/datatype-character

        -- current_city - город, в котором находимся сейчас
        -- Начинаем с города 'a' согласно заданию
        -- ::CHAR(1) приводит к типу "ровно 1 символ"
        'a'::CHAR(1)           AS current_city,
        
        -- accumulated_cost - накопленная стоимость пути ДО ЭТОГО МОМЕНТА
        -- Изначально 0, т.к. мы ещё не двигались
        -- Название "accumulated" подчёркивает, что это НЕ финальная стоимость
        0                      AS accumulated_cost
    
    -- UNION ALL объединяет базу рекурсии с рекурсивным шагом
    -- ALL = не удалять дубликаты (нужны все варианты маршрутов)
    -- Обычный UNION удалил бы дубликаты → потеряли бы часть решений
    UNION ALL
    
    -- ----------------------------------------
    -- РЕКУРСИВНЫЙ ШАГ (recursive member)
    -- Выполняется многократно, пока есть новые строки
    -- ----------------------------------------
    SELECT
        -- Добавляем следующий город к массиву посещённых
        -- || = оператор конкатенации (склеивания) массивов
        -- routes.visited_cities - массив из предыдущей итерации
        -- ARRAY[edges.point2] - новый город, завёрнутый в массив
        -- ::varchar[] обеспечивает совместимость типов
        -- ЧТО ХРАНИТ edges.point2  -  следующий город (куда ведёт ребро)  
        routes.visited_cities || ARRAY[edges.point2]::varchar[],
        

-- -- Текущее состояние:
-- routes.visited_cities = {a,b}
-- routes.current_city = 'b'
-- routes.accumulated_cost = 10

-- -- JOIN нашёл ребро:
-- edges.point1 = 'b'
-- edges.point2 = 'c'  ← СЛЕДУЮЩИЙ ГОРОД!
-- edges.cost = 35

-- -- SELECT создаёт новую строку:
-- новый visited_cities = {a,b} || {c} = {a,b,c}
-- новый current_city = edges.point2 = 'c'
-- новый accumulated_cost = 10 + 35 = 45


        -- Обновляем текущий город
        -- Теперь мы находимся в городе, в который только что пришли
        edges.point2,
        
        -- Увеличиваем накопленную стоимость
        -- accumulated_cost из предыдущей итерации + стоимость перехода
        routes.accumulated_cost + edges.cost
    
    -- FROM указывает источник данных для рекурсивного шага
    -- building_routes - ссылка на РЕЗУЛЬТАТ предыдущей итерации
    -- Алиас routes делает код читабельнее
    FROM building_routes AS routes
    
    -- JOIN соединяет текущий маршрут с возможными следующими рёбрами
    -- Ищем все рёбра, которые НАЧИНАЮТСЯ в текущем городе
    -- tsp AS edges - даём таблице понятный алиас "рёбра"
    -- **Читается:** "Найди все дороги, которые начинаются в нашем текущем городе"
    -- JOIN нужен, чтобы найти ВСЕ ВОЗМОЖНЫЕ СЛЕДУЮЩИЕ ШАГИ из текущего города!
    -- Результат JOIN: Текущие маршруты + возможные шаги
    -- Что делает JOIN? Находит все рёбра, которые начинаются в текущем городе
    --  Условие edges.point1 = routes.current_city означает "найди все дороги, которые начинаются там, где мы сейчас находимся". 🎯
    JOIN tsp AS edges 
      ON edges.point1 = routes.current_city

-- JOIN tsp AS edges ON edges.point1 = routes.current_city
--                      ↑                      ↑
--                      │                      │
--               "откуда ребро"          "где мы сейчас"

-- Означает: "Начало ребра ДОЛЖНО СОВПАДАТЬ с текущим городом"


-- ### Условие JOIN:

-- edges.point1 = routes.current_city

-- Означает:
-- "Начало ребра ДОЛЖНО СОВПАДАТЬ с текущим городом"
-- ```

-- ---

-- ## 💡 НАГЛЯДНЫЙ ПРИМЕР

-- ### Ситуация:
-- ```
-- У нас есть маршрут: {a,b}
-- Мы сейчас в городе: 'b'
-- ```

-- ### Данные в routes (из building_routes):
-- ```
-- ┌──────────────────┬──────────────┬──────────────────┐
-- │ visited_cities   │ current_city │ accumulated_cost │
-- ├──────────────────┼──────────────┼──────────────────┤
-- │ {a,b}            │ b            │ 10               │
-- └──────────────────┴──────────────┴──────────────────┘
--                        ↑
--                   мы ЗДЕСЬ!
-- ```

-- ### Данные в edges (таблица tsp):
-- ```
-- ┌─────────┬─────────┬──────┐
-- │ point1  │ point2  │ cost │
-- ├─────────┼─────────┼──────┤
-- │   a     │   b     │  10  │
-- │   a     │   c     │  15  │
-- │   a     │   d     │  20  │
-- │   b     │   a     │  10  │ ← начинается в 'b' ✅
-- │   b     │   c     │  35  │ ← начинается в 'b' ✅
-- │   b     │   d     │  25  │ ← начинается в 'b' ✅
-- │   c     │   a     │  15  │
-- │   c     │   b     │  35  │
-- │   c     │   d     │  30  │
-- │   d     │   a     │  20  │
-- │   d     │   b     │  25  │
-- │   d     │   c     │  30  │
-- └─────────┴─────────┴──────┘

    
    -- УСЛОВИЕ ПРОДОЛЖЕНИЯ РЕКУРСИИ
    WHERE
        -- Следующий город НЕ должен быть уже посещён
        -- edges.point2 - город, в который хотим пойти
        -- ANY(массив) - агрегатная функция "есть ли элемент в массиве"
        -- NOT ... = ANY(...) эквивалентно "элемента НЕТ в массиве"
        -- 
        -- Это предотвращает:
        -- 1. Повторное посещение городов
        -- 2. Бесконечную рекурсию
        -- 3. Некорректные маршруты
        NOT edges.point2 = ANY(routes.visited_cities)
        
    -- УСЛОВИЕ ОСТАНОВКИ РЕКУРСИИ (неявное):
    -- Когда все города посещены, условие WHERE станет ложным для всех рёбер
    -- → не будет новых строк → рекурсия завершится автоматически
    -- 
    -- PostgreSQL также имеет встроенную защиту от бесконечной рекурсии
    -- (параметр max_recursive_iterations, по умолчанию нет лимита)
),

























-- ============================================
-- ЧАСТЬ 3: ФОРМИРОВАНИЕ ЗАВЕРШЁННЫХ ЦИКЛОВ
-- ============================================

-- Создаём CTE с полными циклами (туры, которые вернулись в 'a')
complete_cycles AS (
    SELECT
        -- Вычисляем ФИНАЛЬНУЮ стоимость маршрута
        -- accumulated_cost - стоимость прохода по всем городам
        -- return_edge.cost - стоимость возврата в начальную точку 'a'
        -- Только здесь получаем ПОЛНУЮ стоимость цикла!
        routes.accumulated_cost + return_edge.cost AS total_cost,
        
        -- Формируем строку маршрута в требуемом формате {a,b,d,c,a}
        -- 
        -- Пошаговое преобразование:
        -- 1. routes.visited_cities = ['a','b','d','c']
        -- 2. || ARRAY['a'] = ['a','b','d','c','a'] (добавили возврат)
        -- 3. array_to_string(..., ',') = "a,b,d,c,a" (массив → строка)
        -- 4. '{' || ... || '}' = "{a,b,d,c,a}" (обрамили фигурными скобками)
        -- 
        -- Почему фигурные скобки: требование задания (формат вывода PostgreSQL)
        '{' || array_to_string(routes.visited_cities || ARRAY['a']::varchar[], ',') || '}' AS tour
    
    -- Источник: маршруты из рекурсивного построения
    FROM building_routes AS routes
    
    -- JOIN для поиска ребра возврата в начальную точку
    -- return_edge - специальный алиас, подчёркивающий роль "ребро возврата"
    JOIN tsp AS return_edge 
      -- Условие 1: ребро начинается в последнем посещённом городе
      ON return_edge.point1 = routes.current_city 
      -- Условие 2: ребро заканчивается в 'a' (возврат домой)
     AND return_edge.point2 = 'a'
    
    -- ПРОВЕРКА ПОЛНОТЫ МАРШРУТА
    WHERE
        -- Проверяем, что посещены ВСЕ города графа
        -- 
        -- array_length(массив, 1) возвращает размер массива
        -- 1 = номер измерения (для одномерных массивов всегда 1)
        -- 
        -- COUNT(DISTINCT point1) считает количество уникальных городов
        -- DISTINCT убирает дубликаты (каждый город встречается дважды в tsp)
        -- 
        -- Если размер массива = количество городов → все посещены!
        -- 
        -- ДИНАМИЧЕСКИЙ ПОДХОД: работает для любого количества городов
        -- Если добавить 5-й город, код не нужно менять
        array_length(routes.visited_cities, 1) = (
            SELECT COUNT(DISTINCT point1) FROM tsp
        )
        
    -- Результат: только маршруты, которые:
    -- 1. Посетили все города
    -- 2. Вернулись в 'a'
    -- 3. Образуют гамильтонов цикл
)




































-- ============================================
-- ЧАСТЬ 4: ФИНАЛЬНАЯ ФИЛЬТРАЦИЯ И ВЫВОД
-- ============================================

-- Выбираем маршруты с минимальной стоимостью
SELECT 
    total_cost,  -- финальная стоимость цикла
    tour         -- маршрут в формате {a,b,d,c,a}
FROM complete_cycles

-- ФИЛЬТРАЦИЯ: только маршруты с минимальной стоимостью
WHERE total_cost = (
    -- Подзапрос вычисляет минимальную стоимость среди всех циклов
    -- MIN - агрегатная функция "минимальное значение"
    -- Выполняется ОДИН РАЗ (PostgreSQL кэширует результат)
    SELECT MIN(total_cost) FROM complete_cycles
)

-- СОРТИРОВКА результатов
-- ORDER BY упорядочивает строки согласно заданию
ORDER BY 
    total_cost,  -- Первичная сортировка: по стоимости (возрастание)
    tour;        -- Вторичная сортировка: по маршруту (лексикографически)
    
-- Лексикографическая сортировка = как в словаре (посимвольно)
-- {a,b,d,c,a} < {a,c,d,b,a} потому что на 3-й позиции 'b' < 'c'

-- ============================================
-- ОЖИДАЕМЫЙ РЕЗУЛЬТАТ
-- ============================================
--
--  total_cost |     tour      
-- ------------+---------------
--          80 | {a,b,d,c,a}
--          80 | {a,c,d,b,a}
-- (2 rows)
--
-- Оба маршрута имеют одинаковую минимальную стоимость 80
-- Они отсортированы лексикографически
-- ============================================
```

