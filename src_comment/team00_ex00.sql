### 1️⃣ **Проверка посещённости города**

```sql
-- Вариант 1: ANY (наш выбор, лучший)
WHERE NOT edges.point2 = ANY(routes.visited_cities)
✅ Идиоматичный PostgreSQL
✅ Самый быстрый
✅ Нет ложных срабатываний

-- Вариант 2: NOT IN с unnest
WHERE edges.point2 NOT IN (
    SELECT unnest(routes.visited_cities)
)
⚠️ Работает, но медленнее
⚠️ Лишний подзапрос

-- Вариант 3: Через строки (ПЛОХО!)
WHERE routes.path_string NOT LIKE '%' || edges.point2 || '%'
❌ Ложные срабатывания ('ab' содержит 'b')
❌ Нужно хранить дополнительную строку
❌ Медленно

-- Вариант 4: NOT EXISTS
WHERE NOT EXISTS (
    SELECT 1 
    FROM unnest(routes.visited_cities) AS city 
    WHERE city = edges.point2
)
⚠️ Избыточно сложно для простой проверки
```

