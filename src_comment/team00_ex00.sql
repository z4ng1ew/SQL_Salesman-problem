### ❓ Вопрос 3: Зачем используете массивы вместо строк?

**Ответ:**
```
Массивы имеют преимущества:

1. ПРОВЕРКА ВХОЖДЕНИЯ:
   NOT point2 = ANY(array)  ← O(n), быстро
   vs
   path NOT LIKE '%b%'      ← может дать ложное срабатывание

2. ДОБАВЛЕНИЕ ЭЛЕМЕНТА:
   array || ARRAY['b']      ← нативная операция
   vs
   path || ',b'             ← нужно парсить строку потом

3. АВТОМАТИЧЕСКИЙ ФОРМАТ:
   array::text выдаёт почти нужный формат
   
4. НАДЁЖНОСТЬ:
   Массивы - строго типизированная структура данных
```

