-- ==========================================

-- Очистка (если таблица существует)
DROP TABLE IF EXISTS tsp CASCADE;

-- ============================================
-- ШАГ 1: СОЗДАЁМ ПРОСТУЮ ТАБЛИЦУ
-- ============================================

-- Таблица с 3 колонками
CREATE TABLE tsp (
    point1 CHAR(1),  -- откуда (из какого города)
    point2 CHAR(1),  -- куда (в какой город)
    cost   INT       -- сколько стоит
);

-- ============================================
-- ШАГ 2: ДОБАВИМ НЕСКОЛЬКО РЁБЕР ДЛЯ ПРИМЕРА
-- ============================================

-- Пример: из города 'a' в город 'b' стоит 10
INSERT INTO tsp VALUES ('a', 'b', 10);

-- Обратный путь тоже стоит 10 (граф неориентированный)
INSERT INTO tsp VALUES ('b', 'a', 10);

-- Ещё одно ребро: a → c = 15
INSERT INTO tsp VALUES ('a', 'c', 15);
INSERT INTO tsp VALUES ('c', 'a', 15);


Основное отличие ориентированного графа (орграфа) от неориентированного заключается в наличии направления у рёбер. В орграфе рёбра (дуги) указывают направление (стрелки), моделируя односторонние отношения. В неориентированном графе рёбра не имеют направления, показывая двухсторонние или симметричные связи.



-- ============================================
-- ШАГ 3: СМОТРИМ ЧТО ПОЛУЧИЛОСЬ
-- ============================================

-- ЗАПРОС 1: Посмотреть ВСЮ таблицу
SELECT * FROM tsp;

-- РЕЗУЛЬТАТ:
--  point1 | point2 | cost 
-- --------+--------+------
--  a      | b      |   10
--  b      | a      |   10
--  a      | c      |   15
--  c      | a      |   15


-- ЗАПРОС 2: Куда можно попасть из города 'a'?
SELECT 
    point2 AS "куда_можно_попасть_из_a",
    cost AS "стоимость"
FROM tsp 
WHERE point1 = 'a';

-- РЕЗУЛЬТАТ:
--  куда_можно_попасть_из_a | стоимость 
-- -------------------------+-----------
--  b                       |        10
--  c                       |        15


-- ЗАПРОС 3: Все маршруты, отсортированные по стоимости
SELECT 
    point1 AS "откуда",
    point2 AS "куда",
    cost AS "стоимость"
FROM tsp 
ORDER BY cost, point1, point2;

-- ============================================
-- ШАГ 4: ДОБАВИМ БОЛЬШЕ ДАННЫХ (ПОЛНЫЙ ГРАФ)
-- ============================================

-- Добавляем остальные рёбра
INSERT INTO tsp VALUES 
('a','d',20), ('d','a',20),
('b','c',35), ('c','b',35),
('b','d',25), ('d','b',25),
('c','d',30), ('d','c',30);

-- Теперь смотрим полный граф
SELECT * FROM tsp ORDER BY point1, point2;

-- РЕЗУЛЬТАТ:
--  point1 | point2 | cost 
-- --------+--------+------
--  a      | b      |   10
--  a      | c      |   15
--  a      | d      |   20
--  b      | a      |   10
--  b      | c      |   35
--  b      | d      |   25
--  c      | a      |   15
--  c      | b      |   35
--  c      | d      |   30
--  d      | a      |   20
--  d      | b      |   25
--  d      | c      |   30


-- ============================================
-- ШАГ 5: ВИЗУАЛИЗАЦИЯ ГРАФА (ТЕКСТОМ)
-- ============================================

-- ЗАПРОС 4: Матрица смежности (кто с кем соединён)
SELECT 
    'Города:' AS info,
    'a, b, c, d' AS список
UNION ALL
SELECT 
    '',
    ''
UNION ALL
SELECT 
    'Из города "' || point1 || '" можно попасть в "' || point2 || '" за ' || cost,
    ''
FROM tsp 
ORDER BY 1;

-- ============================================
-- ШАГ 6: АНАЛИТИЧЕСКИЕ ЗАПРОСЫ
-- ============================================

-- ЗАПРОС 5: Самые дешёвые рёбра
SELECT 
    point1 || ' → ' || point2 AS маршрут,
    cost AS стоимость
FROM tsp
WHERE cost = (SELECT MIN(cost) FROM tsp);

-- РЕЗУЛЬТАТ:
--  маршрут | стоимость 
-- ---------+-----------
--  a → b   |        10
--  b → a   |        10


-- ЗАПРОС 6: Самые дорогие рёбра
SELECT 
    point1 || ' → ' || point2 AS маршрут,
    cost AS стоимость
FROM tsp
WHERE cost = (SELECT MAX(cost) FROM tsp);

-- РЕЗУЛЬТАТ:
--  маршрут | стоимость 
-- ---------+-----------
--  b → c   |        35
--  c → b   |        35


-- ЗАПРОС 7: Средняя стоимость перемещения
SELECT 
    ROUND(AVG(cost), 2) AS средняя_стоимость,
    MIN(cost) AS минимум,
    MAX(cost) AS максимум
FROM tsp;

-- РЕЗУЛЬТАТ:
--  средняя_стоимость | минимум | максимум 
-- -------------------+---------+----------
--              22.50 |      10 |       35


-- ЗАПРОС 8: Сколько уникальных городов в графе?
SELECT COUNT(DISTINCT point1) AS количество_городов
FROM tsp;

-- РЕЗУЛЬТАТ:
--  количество_городов 
-- --------------------
--                   4


-- ЗАПРОС 9: Сколько рёбер выходит из каждого города?
SELECT 
    point1 AS город,
    COUNT(*) AS количество_рёбер,
    SUM(cost) AS общая_стоимость_всех_путей
FROM tsp
GROUP BY point1
ORDER BY point1;

-- РЕЗУЛЬТАТ:
--  город | количество_рёбер | общая_стоимость_всех_путей 
-- -------+------------------+----------------------------
--  a     |                3 |                         45
--  b     |                3 |                         70
--  c     |                3 |                         80
--  d     |                3 |                         75


-- ============================================
-- ШАГ 7: ПОНИМАНИЕ СТРУКТУРЫ ГРАФА
-- ============================================

-- ЗАПРОС 10: Показать как граф выглядит в виде списка смежности
SELECT 
    point1 AS "из_города",
    string_agg(point2 || '(' || cost || ')', ', ' ORDER BY point2) AS "соседи_и_стоимости"
FROM tsp
GROUP BY point1
ORDER BY point1;

-- РЕЗУЛЬТАТ:
--  из_города | соседи_и_стоимости 
-- -----------+--------------------
--  a         | b(10), c(15), d(20)
--  b         | a(10), c(35), d(25)
--  c         | a(15), b(35), d(30)
--  d         | a(20), b(25), c(30)


-- ============================================
-- ШАГ 8: ПРОВЕРКА СИММЕТРИЧНОСТИ ГРАФА
-- ============================================

-- ЗАПРОС 11: Проверяем, что для каждого a→b есть b→a с той же стоимостью
SELECT 
    t1.point1 || ' → ' || t1.point2 AS прямой_путь,
    t1.cost AS стоимость_прямо,
    t2.point1 || ' → ' || t2.point2 AS обратный_путь,
    t2.cost AS стоимость_обратно,
    CASE 
        WHEN t1.cost = t2.cost THEN '✓ симметрично'
        ELSE '✗ НЕ симметрично'
    END AS проверка
FROM tsp t1
JOIN tsp t2 ON t1.point1 = t2.point2 AND t1.point2 = t2.point1
WHERE t1.point1 < t1.point2  -- избегаем дубликатов
ORDER BY t1.point1, t1.point2;

-- РЕЗУЛЬТАТ:
--  прямой_путь | стоимость_прямо | обратный_путь | стоимость_обратно |    проверка     
-- -------------+-----------------+---------------+-------------------+-----------------
--  a → b       |              10 | b → a         |                10 | ✓ симметрично
--  a → c       |              15 | c → a         |                15 | ✓ симметрично
--  a → d       |              20 | d → a         |                20 | ✓ симметрично
--  b → c       |              35 | c → b         |                35 | ✓ симметрично
--  b → d       |              25 | d → b         |                25 | ✓ симметрично
--  c → d       |              30 | d → c         |                30 | ✓ симметрично


