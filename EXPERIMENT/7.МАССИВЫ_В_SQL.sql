-- Можно хранить массивы прямо в таблицах!

DROP TABLE IF EXISTS routes_example;

CREATE TABLE routes_example (
    id INT,
    path varchar[]  -- колонка типа "массив строк"
);

INSERT INTO routes_example VALUES
(1, ARRAY['a','b','c']),
(2, ARRAY['a','c','b']),
(3, ARRAY['a','d','b','c']);

-- Посмотрим что получилось
SELECT * FROM routes_example;

-- Результат:
--  id |   path
-- ----+-----------
--   1 | {a,b,c}
--   2 | {a,c,b}
--   3 | {a,d,b,c}

-- Запросы к массивам в таблице
SELECT 
    id,
    path,
    array_length(path, 1) AS длина_пути,
    'b' = ANY(path) AS проходит_через_b
FROM routes_example;

-- Результат:
--  id |   path    | длина_пути | проходит_через_b
-- ----+-----------+------------+------------------
--   1 | {a,b,c}   |          3 | true
--   2 | {a,c,b}   |          3 | true
--   3 | {a,d,b,c} |          4 | true


-- ============================================
-- ИТОГОВОЕ УПРАЖНЕНИЕ
-- ============================================

SELECT 
    'ИТОГОВОЕ УПРАЖНЕНИЕ: Понимание нашего кода' AS описание;

-- Это то, что происходит в нашем рекурсивном запросе
WITH RECURSIVE simulation AS (
    -- База: начинаем с ['a']
    SELECT 
        ARRAY['a']::varchar[] AS visited,
        'a'::CHAR(1) AS current,
        0 AS iteration
    
    UNION ALL
    
    -- Рекурсия: добавляем следующий город
    SELECT 
        visited || ARRAY['b']::varchar[],
        'b'::CHAR(1),
        iteration + 1
    FROM simulation
    WHERE iteration < 3  -- ограничиваем для примера
)
SELECT 
    iteration AS итерация,
    visited AS посещённые_города,
    current AS текущий_город,
    array_length(visited, 1) AS количество_городов
FROM simulation;

-- Результат:
--  итерация | посещённые_города | текущий_город | количество_городов
-- ----------+-------------------+---------------+--------------------
--         0 | {a}               | a             |                  1
--         1 | {a,b}             | b             |                  2
--         2 | {a,b,b}           | b             |                  3
--         3 | {a,b,b,b}         | b             |                  4